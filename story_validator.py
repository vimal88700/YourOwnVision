# ENDINGS
# ============================================================

@classmethod
def _validate_ending(
    cls,
    ending: Any,
    path: str,
) -> None:

    ending_path = f"{path}.ending"

    if isinstance(
        ending,
        str,
    ):
        if not ending.strip():
            cls.fail(
                f"{ending_path} cannot be empty."
            )
        return

    if not isinstance(
        ending,
        dict,
    ):
        cls.fail(
            f"{ending_path} must be a string or object."
        )

    ending_id = ending.get(
        "id"
    )

    cls._require_id(
        ending_id,
        f"{ending_path}.id",
    )

    text = ending.get(
        "text"
    )

    if not isinstance(
        text,
        str,
    ) or not text.strip():
        cls.fail(
            f"{ending_path}.text must be a non-empty string."
        )

    conditions = ending.get(
        "conditions",
        [],
    )

    if not isinstance(
        conditions,
        list,
    ):
        cls.fail(
            f"{ending_path}.conditions must be a list."
        )

# ============================================================
# CROSS REFERENCES
# ============================================================

@classmethod
def _validate_cross_references(
    cls,
    story: dict[str, Any],
    roles: dict[str, dict[str, Any]],
    scenes: dict[str, dict[str, Any]],
) -> None:

    role_ids = set(roles)
    scene_ids = set(scenes)

    # Every playable role must be usable somewhere in the story.
    playable_roles = {
        role_id
        for role_id, role in roles.items()
        if role.get("playable", True)
    }

    referenced_roles: set[str] = set()

    for scene in scenes.values():

        referenced_roles.update(
            scene.get(
                "eligible_roles",
                [],
            )
        )

        referenced_roles.update(
            scene.get(
                "late_join",
                {},
            ).get(
                "roles",
                [],
            )
        )

        for choice in scene.get(
            "choices",
            [],
        ):
            cls._collect_roles_from_conditions(
                choice.get(
                    "conditions",
                    [],
                ),
                referenced_roles,
            )

            cls._collect_roles_from_effects(
                choice.get(
                    "effects",
                    {},
                ),
                referenced_roles,
            )

        for transition in scene.get(
            "transitions",
            [],
        ):
            cls._collect_roles_from_conditions(
                transition.get(
                    "conditions",
                    [],
                ),
                referenced_roles,
            )

        cls._collect_roles_from_conditions(
            scene.get(
                "late_join",
                {},
            ).get(
                "conditions",
                [],
            ),
            referenced_roles,
        )

        ending = scene.get(
            "ending"
        )

        if isinstance(
            ending,
            dict,
        ):
            cls._collect_roles_from_conditions(
                ending.get(
                    "conditions",
                    [],
                ),
                referenced_roles,
            )

    unknown_referenced_roles = (
        referenced_roles - role_ids
    )

    if unknown_referenced_roles:
        cls.fail(
            "Story contains unknown role references: "
            + ", ".join(
                sorted(unknown_referenced_roles)
            )
        )

    # A playable role that is never available is almost certainly
    # a generation error and should not consume a player slot.
    unused_playable = (
        playable_roles - referenced_roles
    )

    if unused_playable and len(playable_roles) > 1:
        cls.fail(
            "Playable roles are never referenced by the story: "
            + ", ".join(sorted(unused_playable))
        )

    # Every ending must have a meaningful id when represented as
    # an object, and every scene must have either a direct ending
    # or a path toward one. Graph validation below handles paths.
    ending_scenes = [
        scene_id
        for scene_id, scene in scenes.items()
        if scene.get("ending") is not None
    ]

    if not ending_scenes:
        cls.fail(
            "Story must contain at least one ending scene."
        )

@classmethod
def _collect_roles_from_conditions(
    cls,
    conditions: Any,
    output: set[str],
) -> None:

    if not isinstance(
        conditions,
        list,
    ):
        return

    for condition in conditions:

        if not isinstance(
            condition,
            dict,
        ):
            continue

        condition_type = condition.get(
            "type"
        )

        if condition_type == "knowledge":
            role_id = condition.get(
                "role_id"
            )

            if isinstance(
                role_id,
                str,
            ):
                output.add(role_id)

        elif condition_type == "relationship":

            for key in (
                "role_a",
                "role_b",
            ):
                role_id = condition.get(
                    key
                )

                if isinstance(
                    role_id,
                    str,
                ):
                    output.add(role_id)

@classmethod
def _collect_roles_from_effects(
    cls,
    effects: Any,
    output: set[str],
) -> None:

    if not isinstance(
        effects,
        dict,
    ):
        return

    for relationship in effects.get(
        "relationships",
        [],
    ):
        if not isinstance(
            relationship,
            dict,
        ):
            continue

        for key in (
            "role_a",
            "role_b",
        ):
            role_id = relationship.get(
                key
            )

            if isinstance(
                role_id,
                str,
            ):
                output.add(role_id)

    for item in effects.get(
        "knowledge",
        [],
    ):
        if not isinstance(
            item,
            dict,
        ):
            continue

        role_id = item.get(
            "role_id"
        )

        if isinstance(
            role_id,
            str,
        ):
            output.add(role_id)

    for item in effects.get(
        "secrets",
        [],
    ):
        if not isinstance(
            item,
            dict,
        ):
            continue

        owner = item.get(
            "owner"
        )

        if isinstance(
            owner,
            str,
        ):
            output.add(owner)

        revealed_to = item.get(
            "revealed_to",
            [],
        )

        if isinstance(
            revealed_to,
            list,
        ):
            output.update(
                role_id
                for role_id in revealed_to
                if isinstance(
                    role_id,
                    str,
                )
            )

# ============================================================
# GRAPH VALIDATION
# ============================================================

@classmethod
def _validate_story_graph(
    cls,
    story: dict[str, Any],
    scenes: dict[str, dict[str, Any]],
) -> None:

    scene_ids = set(scenes)

    first_scene_id = story.get(
        "first_scene_id"
    )

    if first_scene_id is None:
        first_scene_id = story["scenes"][0]["id"]

    if first_scene_id not in scene_ids:
        cls.fail(
            f"First scene does not exist: {first_scene_id}"
        )

    ending_scenes = {
        scene_id
        for scene_id, scene in scenes.items()
        if scene.get("ending") is not None
    }

    if not ending_scenes:
        cls.fail(
            "Story has no ending scenes."
        )

    graph: dict[str, set[str]] = defaultdict(set)

    for scene_id, scene in scenes.items():

        for choice in scene.get(
            "choices",
            [],
        ):
            target = choice.get(
                "next_scene"
            )

            if target is not None:
                graph[scene_id].add(
                    target
                )

        for transition in scene.get(
            "transitions",
            [],
        ):
            target = transition.get(
                "next_scene"
            )

            if target is not None:
                graph[scene_id].add(
                    target
                )

        entry_scene = scene.get(
            "late_join",
            {},
        ).get(
            "entry_scene"
        )

        if entry_scene is not None:
            graph[scene_id].add(
                entry_scene
            )

    # --------------------------------------------------------
    # Reachability from first scene
    # --------------------------------------------------------

    reachable: set[str] = set()
    stack = [first_scene_id]

    while stack:

        current = stack.pop()

        if current in reachable:
            continue

        reachable.add(current)

        stack.extend(
            graph.get(
                current,
                set(),
            )
            - reachable
        )

    unreachable = scene_ids - reachable

    if unreachable:
        cls.fail(
            "Story contains unreachable scenes: "
            + ", ".join(sorted(unreachable))
        )

    # --------------------------------------------------------
    # Every reachable scene must be able to eventually reach
    # an ending.
    #
    # This prevents Gemini from creating a branch that traps
    # the game forever.
    # --------------------------------------------------------

    reverse_graph: dict[str, set[str]] = defaultdict(set)

    for source, targets in graph.items():
        for target in targets:
            reverse_graph[target].add(
                source
            )

    can_reach_ending = set(
        ending_scenes
    )

    stack = list(
        ending_scenes
    )

    while stack:

        current = stack.pop()

        for previous in reverse_graph.get(
            current,
            set(),
        ):
            if previous not in can_reach_ending:
                can_reach_ending.add(
                    previous
                )
                stack.append(
                    previous
                )

    dead_scenes = (
        reachable - can_reach_ending
    )

    if dead_scenes:
        cls.fail(
            "Story contains reachable scenes that cannot "
            "eventually reach an ending: "
            + ", ".join(sorted(dead_scenes))
        )

    # --------------------------------------------------------
    # Ending scenes should actually terminate the game.
    #
    # Choices may exist for display/final interaction, but no
    # outgoing next_scene is allowed from an ending scene.
    # --------------------------------------------------------

    for scene_id in ending_scenes:

        outgoing = graph.get(
            scene_id,
            set(),
        )

        if outgoing:
            cls.fail(
                f"Ending scene {scene_id} has outgoing scene "
                f"references: {sorted(outgoing)}"
            )

# ============================================================
# PLAYER COUNT
# ============================================================

@classmethod
def _validate_player_count(
    cls,
    roles: dict[str, dict[str, Any]],
    player_count: int | None,
) -> None:

    if player_count is None:
        return

    if not isinstance(
        player_count,
        int,
    ) or isinstance(
        player_count,
        bool,
    ):
        cls.fail(
            "player_count must be an integer."
        )

    if player_count < 1:
        cls.fail(
            "player_count must be at least 1."
        )

    playable_roles = [
        role_id
        for role_id, role in roles.items()
        if role.get(
            "playable",
            True,
        )
    ]

    if player_count > len(playable_roles):
        cls.fail(
            f"Story supports only {len(playable_roles)} playable roles "
            f"but requires {player_count} players."
        )

# ============================================================
# BASIC VALUE VALIDATION
# ============================================================

@classmethod
def _require_id(
    cls,
    value: Any,
    path: str,
) -> None:

    if not isinstance(
        value,
        str,
    ):
        cls.fail(
            f"{path} must be a string."
        )

    value = value.strip()

    if not value:
        cls.fail(
            f"{path} cannot be empty."
        )

    if len(value) > 100:
        cls.fail(
            f"{path} is too long."
        )

@classmethod
def _require_name(
    cls,
    value: Any,
    path: str,
) -> None:

    if not isinstance(
        value,
        str,
    ):
        cls.fail(
            f"{path} must be a string."
        )

    if not value.strip():
        cls.fail(
            f"{path} cannot be empty."
        )

    if len(value) > 200:
        cls.fail(
            f"{path} is too long."
        )

@classmethod
def _validate_json_value(
    cls,
    value: Any,
    path: str,
) -> None:
    """
    Ensure the generated value is JSON-compatible data.

    This intentionally rejects Python-specific values and other
    non-serializable objects before the story reaches Supabase.
    """

    if value is None:
        return

    if isinstance(
        value,
        (str, int, float, bool),
    ):
        return

    if isinstance(
        value,
        list,
    ):
        for index, item in enumerate(value):
            cls._validate_json_value(
                item,
                f"{path}[{index}]",
            )
        return

    if isinstance(
        value,
        dict,
    ):
        for key, item in value.items():

            if not isinstance(
                key,
                str,
            ):
                cls.fail(
                    f"{path} contains a non-string object key."
                )

            cls._validate_json_value(
                item,
                f"{path}.{key}",
            )

        return

    cls.fail(
        f"{path} contains unsupported JSON data: "
        f"{type(value).__name__}"
    )

