# FINGERPRINT
# ============================================================

@classmethod
def structural_fingerprint(
    cls,
    story: dict[str, Any],
) -> str:
    """
    Return a deterministic fingerprint of the story structure.

    Cosmetic text is intentionally excluded where possible.

    The fingerprint is suitable for the database-level unique
    constraint used by story_history.
    """

    validated = cls.validate(
        story
    )

    structural_roles = []

    for role in validated.get(
        "roles",
        [],
    ):
        structural_roles.append(
            {
                "id": role.get("id"),
                "playable": role.get(
                    "playable",
                    True,
                ),
            }
        )

    structural_scenes = []

    for scene in validated.get(
        "scenes",
        [],
    ):

        structural_choices = []

        for choice in scene.get(
            "choices",
            [],
        ):
            structural_choices.append(
                {
                    "id": choice.get("id"),
                    "next_scene": choice.get(
                        "next_scene"
                    ),
                    "branch_priority": choice.get(
                        "branch_priority",
                        0,
                    ),
                    "conditions": cls._canonical_json(
                        choice.get(
                            "conditions",
                            [],
                        )
                    ),
                    "effects": cls._structural_effects(
                        choice.get(
                            "effects",
                            {},
                        )
                    ),
                }
            )

        structural_scenes.append(
            {
                "id": scene.get("id"),
                "timer_seconds": scene.get(
                    "timer_seconds"
                ),
                "eligible_roles": sorted(
                    scene.get(
                        "eligible_roles",
                        [],
                    )
                ),
                "choices": structural_choices,
                "transitions": [
                    {
                        "next_scene": transition.get(
                            "next_scene"
                        ),
                        "conditions": cls._canonical_json(
                            transition.get(
                                "conditions",
                                [],
                            )
                        ),
                    }
                    for transition in scene.get(
                        "transitions",
                        [],
                    )
                ],
                "ending": cls._structural_ending(
                    scene.get(
                        "ending"
                    )
                ),
            }
        )

    structural = {
        "first_scene_id": validated.get(
            "first_scene_id"
        ) or validated["scenes"][0]["id"],
        "roles": structural_roles,
        "scenes": structural_scenes,
    }

    serialized = json.dumps(
        structural,
        sort_keys=True,
        separators=(
            ",",
            ":",
            ),
        ensure_ascii=False,
    )

    return hashlib.sha256(
        serialized.encode(
            "utf-8"
        )
    ).hexdigest()

@classmethod
def _structural_effects(
    cls,
    effects: Any,
) -> Any:

    if not isinstance(
        effects,
        dict,
    ):
        return effects

    cosmetic = {
        "text",
        "description",
    }

    return {
        key: cls._canonical_json(value)
        for key, value in effects.items()
        if key not in cosmetic
    }

@classmethod
def _structural_ending(
    cls,
    ending: Any,
) -> Any:

    if isinstance(
        ending,
        str,
    ):
        return {
            "type": "text"
        }

    if isinstance(
        ending,
        dict,
    ):
        return {
            "id": ending.get(
                "id"
            ),
            "conditions": cls._canonical_json(
                ending.get(
                    "conditions",
                    [],
                )
            ),
        }

    return None

@staticmethod
def _canonical_json(
    value: Any,
) -> Any:
    """
    Produce deterministic JSON-compatible data without changing
    the semantic value.
    """

    if isinstance(
        value,
        dict,
    ):
        return {
            key: StoryValidator._canonical_json(
                value[key]
            )
            for key in sorted(
                value.keys()
            )
        }

    if isinstance(
        value,
        list,
    ):
        return [
            StoryValidator._canonical_json(
                item
            )
            for item in value
        ]

    return value

